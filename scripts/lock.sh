#!/usr/bin/env bash
set -euo pipefail

VLLM_VERSION="${VLLM_VERSION:-0.29.0}"
TORCH_VERSION="${TORCH_VERSION:-2.13.0}"
TORCHVISION_VERSION="${TORCHVISION_VERSION:-0.28.0}"
VLLM_URL="https://github.com/vllm-project/vllm/releases/download/v${VLLM_VERSION}/vllm-${VLLM_VERSION}+cpu-cp38-abi3-manylinux_2_34_x86_64.whl"

cd "$(dirname "$0")/.."
uv pip compile requirements.in \
    --python-version 3.12 --python-platform x86_64-manylinux_2_34 \
    --only-binary :all: --no-header --no-annotate -o /tmp/resolved.txt

{
    echo "# Generated by scripts/lock.sh for vLLM ${VLLM_VERSION} (CPU, Python 3.12, linux/amd64). Do not edit by hand."
    echo "--extra-index-url https://download.pytorch.org/whl/cpu"
    echo "vllm @ ${VLLM_URL}"
    grep -v -E '^(nvidia-|cuda-)' /tmp/resolved.txt \
        | sed -E "s/^torch==${TORCH_VERSION}$/torch==${TORCH_VERSION}+cpu/; s/^torchvision==${TORCHVISION_VERSION}$/torchvision==${TORCHVISION_VERSION}+cpu/"
} > requirements.txt
